// Fallback glyph for bytes the 5x7 font does not cover (e.g. UTF-8 Chinese).
static const unsigned char yw_font_unknown[5] = {0x7F, 0x41, 0x41, 0x41, 0x7F};

// Width/height in pixels for `text` rendered at `scale`.
inline void yw_text_size(const char* text, int scale, int& w, int& h)
{
    size_t n = text ? strlen(text) : 0;
    if (scale < 1) scale = 1;
    w = (int)n * 6 * scale;
    h = 7 * scale;
}

inline void yw_draw_text(YWMat& img, const char* text, int x, int y, int scale,
                         unsigned char r, unsigned char g, unsigned char b)
{
    if (img.empty() || !text) return;
    if (scale < 1) scale = 1;
    int cx = x;
    for (const unsigned char* p = (const unsigned char*)text; *p; ++p)
    {
        const unsigned char* gl = (*p >= 0x20 && *p < 0x7F)
                                      ? yw_font5x7[*p - 0x20]
                                      : yw_font_unknown;
        for (int col = 0; col < 5; col++)
        {
            unsigned char bits = gl[col];
            for (int row = 0; row < 7; row++)
            {
                if (bits & (1 << row))
                    yw_fill_rect(img, cx + col * scale, y + row * scale, scale, scale, r, g, b);
            }
        }
        cx += 6 * scale;
    }
}

// Draw `text` with a solid background plate (used for detection labels).
inline void yw_draw_label(YWMat& img, const char* text, int x, int y, int scale,
                          unsigned char br, unsigned char bg, unsigned char bb,
                          unsigned char fr, unsigned char fg, unsigned char fb)
{
    int tw = 0, th = 0;
    yw_text_size(text, scale, tw, th);
    yw_fill_rect(img, x, y, tw + 4 * scale, th + 4 * scale, br, bg, bb);
    yw_draw_text(img, text, x + 2 * scale, y + 2 * scale, scale, fr, fg, fb);
}

